export type Locale = 'zh-CN' | 'en';
export function localeFromUrl(url: URL): Locale {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return /^\/en(?:\/|$)/.test(url.pathname.slice(base.length)) ? 'en' : 'zh-CN';
}
